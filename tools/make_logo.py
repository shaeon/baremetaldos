#!/usr/bin/env python3
#
# tools/make_logo.py - BM-DOS: the boot logo.
#
# Draws the logo shown in the middle of the boot screen, like the picture of a
# PC BIOS of the nineties, and writes it as src/platform/boot_logo.h: a small
# palette and run-length encoded rows (the kernel decodes it once).  An
# original design: block letters built from bevelled squares, with a blue to
# cyan gradient, "BM-DOS", and a floppy-disk mark beside them.
#
#   python3 tools/make_logo.py            # writes src/platform/boot_logo.h
#   python3 tools/make_logo.py --png x.png  # also a preview
#
# Shaeon (Carlos Palmero) 2026, for BM-DOS by @mmoroca.  GPL-3.0-or-later.

import sys

# 5x7 block letters, drawn for this logo.
GLYPHS = {
    'B': ["XXXX.", "X...X", "X...X", "XXXX.", "X...X", "X...X", "XXXX."],
    'M': ["X...X", "XX.XX", "X.X.X", "X.X.X", "X...X", "X...X", "X...X"],
    '-': [".....", ".....", ".....", "XXXX.", ".....", ".....", "....."],
    'D': ["XXX..", "X..X.", "X...X", "X...X", "X...X", "X..X.", "XXX.."],
    'O': [".XXX.", "X...X", "X...X", "X...X", "X...X", "X...X", ".XXX."],
    'S': [".XXXX", "X....", "X....", ".XXX.", "....X", "....X", "XXXX."],
}

CELL = 8            # one block of a letter, in pixels
GAP = 1             # blocks between letters
TEXT = "BM-DOS"
MARGIN = 6

def lerp(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(3))

def draw():
    letters_w = sum(5 + GAP for _ in TEXT) - GAP
    disk = 9                                    # floppy mark, in blocks
    w = (letters_w + 2 + disk) * CELL + 2 * MARGIN
    h = 7 * CELL + 2 * MARGIN
    img = [[(0, 0, 0)] * w for _ in range(h)]

    top, bottom = (0x55, 0xFF, 0xFF), (0x00, 0x30, 0xD0)

    def block(bx, by, row_t, x0, y0):
        base = lerp(top, bottom, row_t)
        light = lerp(base, (255, 255, 255), 0.55)
        dark = lerp(base, (0, 0, 0), 0.55)
        for y in range(CELL):
            for x in range(CELL):
                px, py = x0 + bx * CELL + x, y0 + by * CELL + y
                if x == 0 or y == 0:
                    c = light
                elif x == CELL - 1 or y == CELL - 1:
                    c = dark
                else:
                    c = base
                img[py][px] = c

    # The letters.
    cx = MARGIN
    for ch in TEXT:
        g = GLYPHS[ch]
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == 'X':
                    block(c, r, r / 6.0, cx, MARGIN)
        cx += (5 + GAP) * CELL

    # A 3.5" floppy, 7x7 blocks: body, shutter, label, write-protect hole.
    fx = cx + CELL
    body = (0x30, 0x30, 0x40); shutter = (0xB8, 0xB8, 0xC8); label = (0xF0, 0xF0, 0xE0)
    for y in range(7 * CELL):
        for x in range(7 * CELL):
            px, py = fx + x, MARGIN + y
            c = body
            if 2 * CELL <= x < 5 * CELL and y < 2 * CELL + CELL // 2:
                c = shutter
                if 3 * CELL + 2 <= x < 4 * CELL - 2 and CELL // 2 <= y < 2 * CELL:
                    c = body
            if CELL <= x < 6 * CELL and 4 * CELL <= y < 7 * CELL - 4:
                c = label
                if y in (4 * CELL + 7, 5 * CELL + 5, 6 * CELL + 3) and CELL + 4 <= x < 6 * CELL - 4:
                    c = (0x50, 0x50, 0xA0)
            if x == 0 or y == 0:
                c = lerp(c, (255, 255, 255), 0.35)
            if (x >= 6 * CELL + CELL // 2 and y < CELL // 2):   # cut corner
                c = (0, 0, 0)
            img[py][px] = c
    return img, w, h

def encode(img, w, h):
    palette = []
    index = {}
    rows = []
    for row in img:
        out = []
        prev, run = None, 0
        for c in row:
            if c not in index:
                index[c] = len(palette)
                palette.append(c)
            i = index[c]
            if i == prev and run < 255:
                run += 1
            else:
                if prev is not None:
                    out += [run, prev]
                prev, run = i, 1
        out += [run, prev]
        rows.append(out)
    assert len(palette) <= 256
    return palette, rows

def main():
    img, w, h = draw()
    palette, rows = encode(img, w, h)
    data = []
    offsets = []
    for r in rows:
        offsets.append(len(data))
        data += r
    lines = []
    lines.append("// boot_logo.h - generated by tools/make_logo.py; do not edit by hand.")
    lines.append("// The BM-DOS boot logo: %dx%d, %d colours, run-length rows (count, index)." % (w, h, len(palette)))
    lines.append("#ifndef BARE_BOOT_LOGO_H\n#define BARE_BOOT_LOGO_H\n")
    lines.append("namespace bootlogo {\n")
    lines.append("constexpr unsigned Width = %d;\nconstexpr unsigned Height = %d;\n" % (w, h))
    lines.append("constexpr unsigned Palette[%d] = {" % len(palette))
    lines.append("  " + ", ".join("0x%06X" % ((c[0] << 16) | (c[1] << 8) | c[2]) for c in palette))
    lines.append("};\n")
    lines.append("constexpr unsigned RowOffset[%d] = {" % h)
    for i in range(0, h, 16):
        lines.append("  " + ", ".join(str(o) for o in offsets[i:i + 16]) + ",")
    lines.append("};\n")
    lines.append("constexpr unsigned char Runs[%d] = {" % len(data))
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
    lines.append("};\n")
    lines.append("} // namespace bootlogo\n\n#endif")
    out = "src/platform/boot_logo.h"
    open(out, "w").write("\n".join(lines) + "\n")
    print("%s: %dx%d, %d colours, %d bytes of runs" % (out, w, h, len(palette), len(data)))

    if "--png" in sys.argv:
        from PIL import Image
        p = Image.new("RGB", (w, h))
        p.putdata([c for row in img for c in row])
        p = p.resize((w * 2, h * 2), Image.NEAREST)
        p.save(sys.argv[sys.argv.index("--png") + 1])

if __name__ == "__main__":
    main()
