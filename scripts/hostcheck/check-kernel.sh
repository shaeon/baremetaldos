#!/bin/sh
#
# Compile the port's own translation units on the host against stand-ins for
# circle-stdlib and the libretro API.  This is the only way kernel.cpp can be
# compiled at all without a cross toolchain and the real Circle tree.
#
# Usage:
#   make check-kernel            # part of make check-host
#
#
# check-kernel.sh - compile the port's own translation units on the host,
# against stand-ins for circle-stdlib and for the libretro API.
#
# Why this exists: kernel.cpp is the one file of ours that neither the real
# build (no toolchain here) nor `make check-platform` (it only covers
# src/platform) will look at.  The .54 round paid for that: a free function
# called CKernel::Report(), which is a member, so the file could not compile -
# and the only way to find out was a five-minute cross build on the Pi.  It was
# found by reading, not by compiling, and that is not a method.
#
# What it compiles: everything in src/ that is ours.  bare_libretro.cpp was
# added after a one-character mistake there ("pData" for the parameter actually
# called "data") broke the board build twice: it includes libretro.h and
# libretro_dosbox.h from third_party, so it was outside every check we could run
# without the toolchain.  scripts/hostcheck/libretro.h is the stand-in.
#
# What it checks, and what it does not:
#
#   * it DOES catch wrong types, wrong call targets, undeclared members,
#     out-of-order declarations, missing includes - everything a compiler
#     knows about our code;
#   * it does NOT catch anything about the real Circle or circle-stdlib: the
#     headers it uses are scripts/hostcheck/circle_stdlib_app.h and
#     scripts/hostcheck/circle/, which declare only what we use, with made-up
#     bodies.  A signature that differs from Circle's real one passes here.
#
# So: a pass means "our code is consistent with the interfaces as documented",
# not "this links on the board".  That is still the difference between finding
# it in two seconds and finding it after a cross build.
#
set -e

DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/../.." && pwd)"

# The simulated Circle headers (types.h, logger.h, scheduler.h, ...) are
# generated by setup.sh, which is what make check-platform runs first.
sh "$DIR/setup.sh" > /dev/null

CXX="${HOST_CXX:-g++}"

# Somewhere for the objects.  -c needs a file, and it must not land in the repo.
OBJ="$(mktemp -t bmdos-check-XXXXXX.o)"
trap 'rm -f "$OBJ"' EXIT

# bare_video.cpp joins the list in .69, and not because it is new: it was the one
# file of ours that no check compiled with warnings on.  check-platform compiles
# it - with -w, and without linking - so .68 shipped a file with THREE warnings
# in it (a static declared and never defined, and the definition reported as
# unused) and the only thing that noticed was the linker, on the board.
#
# The gap is worth naming precisely: check-platform is a symbol check (it wants
# the object file, not the warnings) and check-kernel is an interface check (it
# wants the files that include circle-stdlib and the libretro API).  bare_video
# is neither - it only needs Circle headers - and fell between the two.
for f in main.cpp kernel.cpp platform/bare_video.cpp platform/bare_libretro.cpp \
         platform/bare_thread.cpp; do
	# -Werror is on purpose, and it is safe because this is the HOST check: it
	# never builds the image.  Without it the loop below printed the warning,
	# exited 0 and then announced "(no warnings)" - which is how .68 shipped a
	# file with three of them.  A check that reports and does not fail is a check
	# that says "green".
	# -c and not -fsyntax-only, and the difference is not cosmetic: gcc only
	# reports -Wunused-function when it generates code, and -fsyntax-only stops
	# before that.  .72 shipped a dead ScrollStatus() with this loop saying
	# "no warnings", because the loop could not physically see it.  Verified by
	# compiling a file with one unused static function both ways: -fsyntax-only
	# is silent, -c fails.
	"$CXX" -c -o "$OBJ" -std=gnu++23 -Wall -Wextra -Wpedantic -Werror \
		-I "$DIR" -I "$DIR/fatfs" -I "$ROOT/src" \
		-include "$DIR/circle_stdlib_app.h" \
		-DDOSBOX_SNAPSHOT='"check"' \
		"$ROOT/src/$f"

	echo "$f: compiles against the stand-ins (no warnings)"
done
