#!/usr/bin/env python3
#
# Build the JIT hook as a wrapper translation unit, from bare_dynarec.cpp and
# the core's own headers.
#
# Usage:
#   make check-dynarec-hook      # called by check-dynarec-hook.sh
#
"""gen-dynarec-unit.py - build the JIT hook as a wrapper translation unit.

The problem
-----------
dyn_cache.h keeps the code-cache pointer with internal linkage:

    static Bit8u * cache_code=NULL;        // dyn_cache.h:76

so every translation unit that includes it gets its own copy, and the only copy
that ever points at anything is the one inside the TU that runs cache_init() -
core_dynrec.cpp.  The JIT's pages have to have PXN cleared before the first
translated block runs, and only code that can see that
pointer can do it.

What does NOT work, both tried and both failing at the first line
-----------------------------------------------------------------
  * `-include hook.h`, with the work in an inline function or in a class
    template: an -include'd file is processed before the source, so it cannot
    see a declaration the source's own includes make.  g++ says so:
        "'cache_code' was not declared in this scope"
  * an extra TU that includes dyn_cache.h: it does compile - if you also supply
    the macros and the `core_dynrec` struct that core_dynrec.cpp defines before
    including it - but it produces a *second* copy of cache_code, initialised to
    null, and reads that.  A pointer to nothing, silently.

What does work is to be in the same TU, and the only way in without editing
upstream's file is to **compile a file that #includes it**:

    #include "core_dynrec.cpp"      <- the whole engine, unchanged
    ... our hook, which can see cache_code ...

That is this generator.  The generated file is what the Makefile compiles
*instead of* $(DOSBOX_DIR)/src/cpu/core_dynrec.cpp, never in addition to it: two
copies of the engine would be two symbols for everything it defines.

Why a macro and not a redefinition of cache_init()
--------------------------------------------------
cache_init() is `static` and its call site is inside the same file, so the only
way to run our code at that moment without rewriting the function is to let the
preprocessor rename the calls as the file is compiled:

    -DCPU_Core_Dynrec_Cache_Init=BareDynrecCacheInitOriginal

A command-line macro is used rather than a #define in this generated file on
purpose: it applies from the very first line of core_dynrec.cpp, including its
own prototypes at the top, so declaration and definition are renamed together
and nothing is left half-renamed.  (Explaining the failed attempt and then the
working one in the same place is the point of this docstring.)

The result
----------
    CPU_Core_Dynrec_Cache_Init(bool)          -> ours: calls the original
                                                 through the renamed symbol,
                                                 then makes the cache
                                                 executable, then says so
    BareDynrecCacheInitOriginal(bool)         -> the genuine cache_init()
                                                 wrapper, as upstream wrote it

and `cache_code`, `CACHE_TOTAL` and `CACHE_MAXSIZE` are visible to ours because
they are in the same translation unit.

Checked, not assumed
--------------------
The two properties this depends on are properties of the pinned revision, and
`make check-dynarec` fails on the host if they change:
  * core_dynrec.cpp includes dyn_cache.h with that exact spelling;
  * dyn_cache.h declares cache_code at namespace scope as `static Bit8u *`.

Usage: gen-dynarec-unit.py <output-file> <dosbox-dir>
"""

import pathlib
import sys

TEMPLATE = """//
// bare_dynrec_unit.cpp - GENERATED by scripts/hostcheck/gen-dynarec-unit.py.
// Do not edit; edit the generator.  Compiled INSTEAD OF
// $(DOSBOX_DIR)/src/cpu/core_dynrec.cpp, never as well as.
//
// Why it exists: see the generator's docstring.  The short version is that
// dyn_cache.h's `cache_code` has internal linkage, so the hook has to be in the
// same translation unit as the engine, and the only way in is to include it.
//
// -DCPU_Core_Dynrec_Cache_Init=BareDynrecCacheInitOriginal is supplied by the
// Makefile, so the engine's own prototype and its definition are both renamed
// and this file is free to define the original name.
//
// Emitted by: %(generator)s
// DOSBox tree: %(dosbox)s
//
#include <circle/logger.h>
#include <circle/types.h>

// The name is resolved by path, not by luck: core_dynrec.cpp lives in
// $(DOSBOX_DIR)/src/cpu and that path is NOT in DOSBOX_INCLUDES (if it were,
// every core header would come in by bare name and they would collide). Here it
// goes in with the full path, generated from the tree the generator is given, so
// that the file works whoever compiles it.
#include "%(engine_include)s"

// The Makefile's -D renamed every use of the name, including the one this file
// defines below.  Undo it here: from this point the name is ours to define, and
// the genuine function keeps the renamed spelling upstream's definition gave it.
#undef CPU_Core_Dynrec_Cache_Init

static const char FromDynarec[] = "dynarec";

// Declared here, defined in src/platform/bare_dynarec.cpp: clears PXN on the
// pages covering the range, synchronises the instruction stream, and returns
// FALSE if the page tables are not what it expects.
extern "C" bool BareDynarecPrepareCodeCache (void *pCache, unsigned nBytes);

/// \brief cache_init() as upstream wrote it, renamed by the Makefile's -D.
void BareDynrecCacheInitOriginal (bool enable_cache);

/// \brief CPU_Core_Dynrec_Cache_Init(): the original, plus executable pages.
///
/// Called from cpu.cpp when the machine switches to the dynamic core (the
/// "core=dynamic" path in particular), and from nowhere else.  It runs once per
/// machine start, before the first block is translated.
void CPU_Core_Dynrec_Cache_Init (bool enable_cache)
{
\tBareDynrecCacheInitOriginal (enable_cache);

\tif (!enable_cache)
\t{
\t\t// "Cache off" is not an event with a cache behind it.
\t\treturn;
\t}

\tif (cache_code == nullptr)
\t{
\t\t// cache_init() is supposed to have set this.  If it has not, upstream
\t\t// changed and the JIT must not run: executing from a page with PXN = 1
\t\t// on this machine is a fault with no message on screen.
\t\tCLogger::Get ()->Write (FromDynarec, LogError,
\t\t\t"dynrec: cache_init() left cache_code null; not using the JIT");
\t\treturn;
\t}

\t// Exactly what cache_init() asked malloc() for, and not one byte more:
\t//
\t//     malloc (CACHE_TOTAL + CACHE_MAXSIZE + PAGESIZE_TEMP - 1 + PAGESIZE_TEMP)
\t//
\t// The -1 is malloc's worst-case slack from aligning the buffer to a page, so
\t// this is the whole allocation; the walk rounds both ends to page
\t// boundaries anyway, which covers the slack either way.
\t//
\t// Hand-writing the range is how this first said `+ 2 * PAGESIZE_TEMP` - the
\t// slack added instead of subtracted, 1.8 KB past the end of the allocation.
\t// That is a page belonging to whoever malloc() put next, and clearing its
\t// PXN would have made a stranger's memory executable.  A check compares this
\t// expression against the engine's own, as numbers.
\tconst unsigned nBytes = CACHE_TOTAL + CACHE_MAXSIZE + (2 * PAGESIZE_TEMP) - 1;

\tconst bool bOk = BareDynarecPrepareCodeCache (cache_code_start_ptr, nBytes);

\tif (bOk)
\t{
\t\tCLogger::Get ()->Write (FromDynarec, LogNotice,
\t\t\t"dynrec: code cache at 0x%%llx: %%u KB executable, %%u KB of blocks",
\t\t\t(unsigned long long) (uintptr) cache_code,
\t\t\tnBytes / 1024,
\t\t\t(unsigned) (CACHE_BLOCKS * sizeof (CacheBlockDynRec)) / 1024);
\t}
\telse
\t{
\t\tCLogger::Get ()->Write (FromDynarec, LogError,
\t\t\t"dynrec: cannot make the code cache executable - the JIT would "
\t\t\t"fault on its first block, so keep core=normal");
\t}
}

/// \\brief Forget the code cache, for a machine built again in the same process
/// (the port's DOS restart, bare_libretro.cpp BareCoreRestart).
///
/// Upstream's cache_close() is empty (its body is commented out) and
/// cache_initialized stays true, so the next cache_init() returns at once and
/// the new machine would run on the old machine's translated blocks - and on
/// code page handlers that point into the old machine's memory, which the
/// cache puts back into the page tables when it recycles a page.  Called after
/// the old machine is gone: the page handlers are deleted without being
/// released (ClearRelease would write the dead paging tables), and the blocks
/// and the code memory are freed, so that cache_init() builds everything again
/// and CPU_Core_Dynrec_Cache_Init above makes the new memory executable.
extern "C" void BareDynrecCacheForget (void)
{
\tfor (CodePageHandlerDynRec *p = cache.used_pages; p != nullptr; )
\t{
\t\tCodePageHandlerDynRec *pNext = p->next;
\t\tdelete p;
\t\tp = pNext;
\t}
\tfor (CodePageHandlerDynRec *p = cache.free_pages; p != nullptr; )
\t{
\t\tCodePageHandlerDynRec *pNext = p->next;
\t\tdelete p;
\t\tp = pNext;
\t}
\tcache.used_pages = nullptr;
\tcache.free_pages = nullptr;
\tcache.last_page = nullptr;

\tfree (cache_blocks);
\tcache_blocks = nullptr;
\tfree (cache_code_start_ptr);
\tcache_code_start_ptr = nullptr;
\tcache_code = nullptr;
\tcache_code_link_blocks = nullptr;
\tcache_initialized = false;

\tCLogger::Get ()->Write (FromDynarec, LogNotice, "dynrec: code cache forgotten for a restart");
}
"""


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2

    out = pathlib.Path(sys.argv[1])
    dosbox = pathlib.Path(sys.argv[2])

    engine = dosbox / "src" / "cpu" / "core_dynrec.cpp"
    dyn_cache = dosbox / "src" / "cpu" / "dyn_cache.h"

    problems = []

    if not engine.is_file():
        problems.append(f"missing {engine}")
    else:
        text = engine.read_text(errors="replace")
        if '#include "dyn_cache.h"' not in text:
            problems.append("core_dynrec.cpp no longer includes dyn_cache.h")
        if "CPU_Core_Dynrec_Cache_Init" not in text:
            problems.append("core_dynrec.cpp lost CPU_Core_Dynrec_Cache_Init")

    if not dyn_cache.is_file():
        problems.append(f"missing {dyn_cache}")
    else:
        text = dyn_cache.read_text(errors="replace")
        if "static Bit8u * cache_code=NULL;" not in text:
            problems.append("dyn_cache.h: cache_code is not the namespace-scope "
                            "static this hook relies on")
        if "PAGESIZE_TEMP" not in text:
            problems.append("dyn_cache.h: PAGESIZE_TEMP has moved")
        if "static void cache_init(bool enable) {" not in text:
            problems.append("dyn_cache.h: cache_init() is no longer the static "
                            "function this hook renames")

    if problems:
        print("gen-dynarec-unit: the pinned core is no longer what this hook assumes:")
        for p in problems:
            print(f"  - {p}")
        print("Review the JIT hook before building for the board.")
        return 1

    # Ruta absoluta a la ruta del motor, resuelta: el fichero generado se
    # compila desde el directorio del proyecto, pero con esto da igual desde
    # donde se compile (y el banco de pruebas lo compila desde /tmp).
    engine_include = str(engine.resolve())
    out.write_text(TEMPLATE % {"generator": "gen-dynarec-unit.py",
                               "dosbox": dosbox,
                               "engine_include": engine_include})
    print(f"gen-dynarec-unit: {out} ({len(TEMPLATE.splitlines())} lineas)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
